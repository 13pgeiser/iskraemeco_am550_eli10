def crc16(data):
    crc = 0xFFFF
    for c in data:
        crc ^= c
        for _ in range(8):
            if (crc & 1) > 0:
                crc = (crc >> 1) ^ 0x8408
            else:
                crc = crc >> 1
        crc &= 0xFFFF
    crc = ~crc
    return crc & 0xFFFF

